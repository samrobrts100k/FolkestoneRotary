// One-off: extracts the CSS of design-demos/demo-site.html and scopes it under `.dx` for the real site.
// Usage: node scripts/port-demo-css.mjs  (writes app/dx.css)
import fs from "node:fs";
import postcss from "postcss";

const html = fs.readFileSync("design-demos/demo-site.html", "utf8");
const css = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");
const root = postcss.parse(css);

const frames = new Set();
root.walkAtRules(/keyframes$/, (a) => frames.add(a.params));
const prefixName = (n) => (frames.has(n) ? `dx-${n}` : n);

const scope = (sel) =>
  sel.split(",").map((s) => s.trim()).filter(Boolean).map((s) => {
    if (s === ":root" || s === "html" || s === "body") return ".dx";
    if (s === "*") return ".dx *";
    if (/^(html|body)\b/.test(s)) return s.replace(/^(html|body)\s*/, ".dx ");
    return `.dx ${s}`;
  }).join(",");

root.walkRules((rule) => {
  if (rule.parent && rule.parent.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  rule.selector = scope(rule.selector);
});
root.walkAtRules(/keyframes$/, (a) => { a.params = prefixName(a.params); });
root.walkDecls(/^animation(-name)?$/, (d) => {
  d.value = d.value.replace(/[A-Za-z_][\w-]*/g, (w) => (frames.has(w) ? `dx-${w}` : w));
});
root.walkDecls((d) => {
  d.value = d.value
    .replace(/"Source Serif 4",\s*Georgia,\s*serif/g, "var(--font-serif),Georgia,serif")
    .replace(/"Source Sans 3",\s*system-ui,\s*sans-serif/g, "var(--font-sans),system-ui,sans-serif")
    .replace(/"Source Sans 3",\s*sans-serif/g, "var(--font-sans),system-ui,sans-serif")
    .replace(/"Source Serif 4",\s*serif/g, "var(--font-serif),Georgia,serif");
});
let out = root.toString()
  .replace(/#p-join\.on \.sit/g, ".tbl.in .sit")   // seats appear when the table scrolls into view
  .replace(/\.ring\b/g, ".vring");                   // .ring is also a Tailwind utility
fs.writeFileSync("app/dx.css", "/* Generated by scripts/port-demo-css.mjs from design-demos/demo-site.html. Everything is scoped under .dx. */\n" + out);
console.log("frames:", [...frames].join(" "));
